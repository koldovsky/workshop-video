#!/usr/bin/env python3
"""Create a local, self-contained player page only from hash-bound verified media."""
import argparse
import html
import json
from pathlib import Path
import re
import tempfile
from urllib.parse import urlsplit
from verify_video import ASSETS, digest
from render_integrity import check_render


def clock(seconds):
    value = round(seconds)
    return f'{value//3600:02}:{value//60%60:02}:{value%60:02}'


def check_verified(work):
    plan = json.loads((work/'timeline.json').read_text(encoding='utf-8'))
    report = json.loads((work/'verification.json').read_text(encoding='utf-8'))
    check_render(work, plan)
    if (report.get('fullDecodePass') is not True
            or report.get('expectedDurationSeconds') != plan['duration']
            or abs(report.get('durationSeconds', -100) - plan['duration']) > .12
            or report.get('frames') != round(plan['duration'] * plan['fps'])
            or report.get('timelineSha256') != digest(work/'timeline.json')
            or report.get('renderManifestSha256') != digest(work/'render-manifest.json')):
        raise ValueError('Final video verification is missing or stale')
    for name in ASSETS:
        if report['assets'].get(name) != digest(work/name):
            raise ValueError('Unverified or changed video asset: '+name)
    return plan, report


def safe_output(destination, name, replace):
    """Preflight every destination before writing; preserve unrelated existing material."""
    destination = destination.absolute()
    if destination.is_symlink() or (destination.exists() and not destination.is_dir()):
        raise ValueError('Publication destination must be a real directory')
    directory = destination/(name+'-media')
    page = destination/(name+'.html')
    marker = directory/'.workshop-video.json'
    targets = [page, marker, directory/'manifest.json', *(directory/a for a in ASSETS)]
    if directory.is_symlink() or (directory.exists() and not directory.is_dir()):
        raise ValueError('Media output must be a real directory, not a symlink')
    for target in targets:
        if target.is_symlink() or (target.exists() and not target.is_file()):
            raise ValueError('Output file must not be a symlink or directory: '+str(target))
        if not target.resolve().is_relative_to(destination.resolve()):
            raise ValueError('Output escapes publication directory')
    if page.exists() or directory.exists():
        if not replace:
            raise FileExistsError('Output already exists; use --replace for owned generated output')
        if directory.exists():
            if not marker.is_file():
                raise ValueError('Existing media directory is not owned by workshop-video')
            ownership = json.loads(marker.read_text(encoding='utf-8'))
            if ownership != {'generator': 'workshop-video', 'name': name, 'formatVersion': 1}:
                raise ValueError('Media ownership marker does not match')
        if page.exists() and '<!-- generated by workshop-video -->' not in page.read_text(encoding='utf-8')[:256]:
            raise ValueError('Existing page is not owned by workshop-video')
    return destination, directory, page


def atomic_bytes(path, data):
    handle, temporary = tempfile.mkstemp(prefix='.workshop-video-', dir=path.parent)
    import os
    try:
        with os.fdopen(handle, 'wb') as stream:
            stream.write(data)
        Path(temporary).replace(path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def publish(work, destination, name='lesson', replace=False):
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]{0,70}', name):
        raise ValueError('Use a safe plain filename for --name')
    plan, report = check_verified(work)
    destination, directory, page_path = safe_output(destination, name, replace)
    esc = lambda value: html.escape(str(value), quote=True)
    labels = plan.get('labels', {})
    label = lambda key, fallback: esc(labels.get(key, fallback))
    navigation = []
    for link in plan.get('links', []):
        target = link['href']
        parsed = urlsplit(target)
        if (not target or parsed.scheme not in ('', 'http', 'https') or target.startswith('//')
                or '\\' in target or any(ord(c) < 32 for c in target)):
            raise ValueError('Navigation links must be ordinary relative or HTTP(S) URLs')
        navigation.append(f'<a href="{esc(target)}">{esc(link["label"])}</a>')
    media = name+'-media'
    directory.mkdir(parents=True, exist_ok=True)
    manifest = {}
    for filename in ASSETS:
        source = work/filename
        atomic_bytes(directory/filename, source.read_bytes())
        manifest[filename] = {'bytes': source.stat().st_size, 'sha256': digest(source)}
    atomic_bytes(directory/'manifest.json', (json.dumps(manifest, indent=2)+'\n').encode('utf-8'))
    atomic_bytes(directory/'.workshop-video.json', (json.dumps({'generator': 'workshop-video', 'name': name, 'formatVersion': 1})+'\n').encode('utf-8'))
    chapters = ''.join(f'<li><button type="button" data-time="{c["start"]}"><time>{clock(c["start"])}</time> {esc(c["title"])}</button></li>' for c in plan['chapters'])
    transcript = []
    for chapter in plan['chapters']:
        paragraphs = ''.join('<h3>'+esc(s['title'])+'</h3><p>'+esc(s['narration'])+'</p>'
                             for s in plan['segments'] if s['chapterId'] == chapter['id'])
        transcript.append('<details><summary>'+clock(chapter['start'])+' · '+esc(chapter['title'])+'</summary>'+paragraphs+'</details>')
    size = manifest['lesson.mp4']['bytes']/1024/1024
    page = f'''<!doctype html><!-- generated by workshop-video --><html lang="{esc(plan['language'])}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{esc(plan['title'])}</title><style>
:root{{color-scheme:dark;--bg:#080d11;--ink:#e7eef2;--muted:#afc0cb;--line:#2a3f4b;--accent:#52df9a}}*{{box-sizing:border-box}}body{{margin:0;background:var(--bg);color:var(--ink);font:17px/1.65 system-ui,sans-serif}}main{{max-width:1180px;margin:auto;padding:28px 24px}}a{{color:#57d5e2;text-underline-offset:3px}}nav,.downloads{{display:flex;gap:12px 22px;flex-wrap:wrap;margin:0 0 25px}}nav{{border-bottom:1px solid var(--line);padding-bottom:20px}}h1{{font-size:clamp(30px,5vw,48px);line-height:1.15}}h2{{font-size:27px}}h3{{font-size:19px}}.brand{{letter-spacing:2px;color:var(--accent);font-size:13px}}.intro,.note{{color:var(--muted)}}video{{display:block;width:100%;aspect-ratio:16/9;background:#000;border:1px solid var(--line);border-radius:9px;margin:26px 0 15px}}.downloads a{{padding:10px 16px;border:1px solid var(--line);border-radius:6px;text-decoration:none}}.chapters{{list-style:none;padding:0;columns:2;column-gap:35px}}.chapters li{{break-inside:avoid;margin:0 0 8px}}button{{background:none;border:0;color:var(--ink);font:inherit;text-align:left;cursor:pointer;padding:7px 0;line-height:1.45}}time{{color:var(--accent);font:14px monospace;margin-right:8px}}details{{border:1px solid var(--line);border-radius:7px;margin:12px 0;padding:14px 18px}}summary{{cursor:pointer;font-weight:600}}details p{{color:var(--muted);max-width:96ch}}button:focus-visible,a:focus-visible,summary:focus-visible{{outline:3px solid var(--accent);outline-offset:4px}}@media(max-width:700px){{.chapters{{columns:1}}main{{padding:22px 16px}}}}
</style></head><body><main>
<nav aria-label="{label('materials', 'Workshop materials')}">{''.join(navigation)}</nav>
<p class="brand">{esc(plan['brand'])}</p><h1>{esc(plan['title'])}</h1>
<p class="intro">{esc(plan['description'])}</p><p class="note">{esc(plan['disclosure'])} · {clock(plan['duration'])}</p>
<video id="video" controls preload="metadata" playsinline poster="{media}/poster.png"><source src="{media}/lesson.mp4" type="video/mp4">{label('videoFallback', 'Download the MP4 below to play it locally.')}</video>
<div class="downloads"><a download href="{media}/lesson.mp4">{label('downloadVideo', 'Download MP4')} · {size:.1f} MiB</a><a download href="{media}/lesson.srt">SRT</a><a download href="{media}/lesson.vtt">VTT</a><a download href="{media}/transcript.md">{label('transcript', 'Transcript')}</a></div>
<h2>{label('chapters', 'Chapters')}</h2><ol class="chapters">{chapters}</ol>
<h2>{label('transcript', 'Transcript')}</h2>{''.join(transcript)}
</main><script>const video=document.getElementById('video');document.querySelectorAll('[data-time]').forEach(button=>button.addEventListener('click',()=>{{video.currentTime=Number(button.dataset.time);video.scrollIntoView({{behavior:matchMedia('(prefers-reduced-motion: reduce)').matches?'auto':'smooth',block:'center'}});video.play().catch(()=>{{}});}}));</script></body></html>'''
    atomic_bytes(page_path, page.encode('utf-8'))
    print('VIDEO_PUBLISHED_LOCAL', destination/(name+'.html'))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--work', type=Path, required=True)
    parser.add_argument('--destination', type=Path, required=True)
    parser.add_argument('--name', default='lesson')
    parser.add_argument('--replace', action='store_true', help='Replace only this skill\'s existing generated page/media')
    args = parser.parse_args()
    publish(args.work.resolve(), args.destination.absolute(), args.name, args.replace)
